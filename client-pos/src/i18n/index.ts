const getInitialLanguage = () => {
  try {
    const stored = localStorage.getItem('pos_language')
    if (stored && ['id', 'en', 'zh'].includes(stored)) {
      return stored
    }
  } catch (e) {
    // ignore
  }
  return 'id'
}

