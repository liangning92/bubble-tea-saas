"""Enter an account/channel-specific OS sandbox, then run native Hermes.

No host HOME, browser profile, production credentials, database or other account's
memory is mounted into the native process. macOS uses its existing sandbox-exec;
an unsupported host fails before model/tool execution instead of silently running
unconfined. Linux deployment must provide an equivalent reviewed sandbox launcher.
"""
from __future__ import annotations
import contextlib
import fcntl
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys,stat
import tempfile
from urllib.parse import urlsplit


def _path(value):
    path=Path(value)
    if not path.is_absolute() or path.is_symlink() or path.resolve()!=path:
        raise ValueError('NATIVE_CANONICAL_PATH_REQUIRED')
    return path


def macos_policy(profile, source, repository, python_prefix, provider_url):
    """Generated by the trusted host, never from model-written policy text."""
    def q(value): return json.dumps(str(value),ensure_ascii=False)
    parsed=urlsplit(provider_url)
    if parsed.scheme!='http' or parsed.hostname not in {'127.0.0.1','localhost','::1'} or parsed.username or parsed.password or not parsed.port:
        raise ValueError('NATIVE_PRIVATE_PROVIDER_RELAY_REQUIRED')
    reads=[Path('/System'),Path('/usr'),Path('/bin'),Path('/sbin'),Path('/dev'),Path('/private/etc'),Path('/Library/Apple'),source,repository/'scripts'/'hermes_employee',python_prefix,Path(sys.prefix).resolve()]
    return '\n'.join(['(version 1)','(deny default)','(allow process*)','(allow sysctl-read)','(allow file-read-metadata)',
        '(allow file-read-data (literal "/"))',
        '(allow mach-lookup (global-name "com.apple.system.logger") (global-name "com.apple.logd") (global-name "com.apple.system.notification_center") (global-name "com.apple.cfprefsd.agent") (global-name "com.apple.cfprefsd.daemon"))',
        *['(allow file-read* (subpath '+q(p)+'))' for p in reads],
        '(allow file-read* file-write* (subpath '+q(profile)+'))',
        # Source checkout must never become a back door to its developer .env.
        '(deny file-read* (regex #"/(\\.env(\\.[^/]*)?|auth\\.json|credentials\\.json)$"))',
        # Arbitrary internet writes could bypass the account's output policy.
        # Until an account-authorized egress broker is connected, only the
        # existing scoped provider relay is reachable (no direct paid fallback).
        '(allow network-outbound (remote tcp "localhost:'+str(parsed.port)+'"))'])


def launch_native(first, wire_out):
    ticket,config=first['ticket'],first['config']
    namespace=ticket.get('native',{}).get('memoryNamespace','')
    if len(namespace)!=64 or any(c not in 'abcdef0123456789' for c in namespace): raise ValueError('NATIVE_MEMORY_NAMESPACE_INVALID')
    root=_path(config['isolatedRoot'])
    if root.stat().st_mode&0o077: raise ValueError('NATIVE_PRIVATE_ROOT_REQUIRED')
    profiles=root/'native_profiles';profiles.mkdir(mode=0o700,exist_ok=True);_path(profiles)
    profile=profiles/namespace
    profile.mkdir(mode=0o700,exist_ok=True);_path(profile)
    if profile.stat().st_mode&0o077:raise ValueError('NATIVE_PRIVATE_PROFILE_REQUIRED')
    for name in ['home','tmp','workspace']:
        folder=profile/name;folder.mkdir(mode=0o700,exist_ok=True);_path(folder)
    # Entire profile belongs to this actual channel+account-policy namespace.
    # Simultaneous sessions may not overwrite each other's native memory files.
    lock_fd=os.open(profile/'.native-session.lock',os.O_RDWR|os.O_CREAT|os.O_NOFOLLOW,0o600)
    lock_stat=os.fstat(lock_fd)
    if not stat.S_ISREG(lock_stat.st_mode) or lock_stat.st_nlink!=1 or lock_stat.st_uid!=os.getuid():
        os.close(lock_fd);raise ValueError('NATIVE_PROFILE_LOCK_INVALID')
    with os.fdopen(lock_fd,'a+') as lease:
        fcntl.flock(lease.fileno(),fcntl.LOCK_EX)
        canary=root/('native-host-canary-'+ticket['executionId'])
        fd=os.open(canary,os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW,0o600)
        with os.fdopen(fd,'w') as f:f.write(os.urandom(32).hex())
        try:
            if sys.platform!='darwin' or not Path('/usr/bin/sandbox-exec').is_file():
                raise RuntimeError('NATIVE_OS_SANDBOX_LAUNCHER_UNAVAILABLE')
            source=_path(config['hermesSource'])
            repository=Path(__file__).resolve().parents[2]
            policy=macos_policy(profile,source,repository,Path(sys.base_prefix).resolve(),config['providerBaseUrl'])
            config={**config,'nativeSandbox':{'profile':str(profile),'canary':str(canary)}}
            # No model credentials in argv/env; the existing execution-scoped
            # bearer travels over stdin and can use only its bound backend relay.
            child=subprocess.Popen(['/usr/bin/sandbox-exec','-p',policy,sys.executable,'-I','-B',str(Path(__file__).resolve()),'--inside'],
                stdin=subprocess.PIPE,stdout=subprocess.PIPE,stderr=sys.stderr,text=True,bufsize=1,
                cwd=profile/'workspace',env={'PATH':'/usr/bin:/bin','HOME':str(profile/'home'),'TMPDIR':str(profile/'tmp'),'PYTHONDONTWRITEBYTECODE':'1','PYTHONUNBUFFERED':'1','NO_PROXY':'*'})
            child.stdin.write(json.dumps({'ticket':ticket,'config':config})+'\n');child.stdin.flush()
            # The native child already serializes frame/receipt pairs across all
            # its threads. Forward unchanged; only final frames have no response.
            for line in child.stdout:
                frame=json.loads(line)
                wire_out.write(line);wire_out.flush()
                if frame.get('method')=='finished':continue
                response=sys.stdin.readline()
                if not response:break
                child.stdin.write(response);child.stdin.flush()
            code=child.wait()
            if code:raise RuntimeError('NATIVE_SANDBOX_CHILD_FAILED_'+str(code))
        finally:
            if 'child' in locals() and child.poll() is None:
                child.terminate();child.wait(timeout=10)
            canary.unlink(missing_ok=True)


def inside():
    first=json.loads(sys.stdin.readline())
    # Some native progress emitters write to sys.__stdout__ or directly to fd 1.
    # Give framed RPC a dedicated duplicate, then redirect fd 1 itself; a text
    # redirect alone would let a child's progress corrupt another RPC receipt.
    wire_out=os.fdopen(os.dup(sys.stdout.fileno()),'w',buffering=1,encoding='utf-8')
    os.dup2(sys.stderr.fileno(),sys.stdout.fileno())
    sys.path.insert(0,str(Path(__file__).resolve().parent))
    from native_runtime import run_native_ticket,SerializedRpc
    import httpx
    def rpc(method,params):
        wire_out.write(json.dumps({'protocol':'employee_work_trace_v1','method':method,'params':params},ensure_ascii=False)+'\n');wire_out.flush()
        response=json.loads(sys.stdin.readline())
        if set(response)!={'result'}:raise RuntimeError('NATIVE_HOST_RECEIPT_REQUIRED')
        return response['result']
    with contextlib.redirect_stdout(sys.stderr):
        result=run_native_ticket(first['ticket'],first['config'],SerializedRpc(rpc),provider_send=httpx.Client.send)
    wire_out.write(json.dumps({'protocol':'employee_work_trace_v1','method':'finished','params':result},ensure_ascii=False,default=str)+'\n');wire_out.flush()


if __name__=='__main__':
    if sys.argv[1:]!=['--inside']:raise RuntimeError('NATIVE_HOST_PRIVATE_ENTRY_REQUIRED')
    inside()
