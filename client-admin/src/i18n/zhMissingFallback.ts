/**
 * Initialize the zh missing fallback into i18next.
 * Call this once at app startup (before React renders).
 */
export function initZhMissingFallback() {
  try {
    Object.entries(zhMissingFallback).forEach(([namespace, translations]) => {
      i18next.addResourceBundle('zh', namespace, translations, true, true)
    })
    console.log('[zhFallback] Added', Object.keys(zhMissingFallback).length, 'missing namespaces to zh bundle')
  } catch (e) {
    console.error('[zhFallback] Failed to add missing translations:', e)
  }
}
